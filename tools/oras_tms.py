#!/usr/bin/env python3
# ORAS's TM / HM compatibility (version group 16, method 4 = machine) from tools/.cache/pokemon_moves.csv: {dex: [move ids]} for 1-721's
# own forms, on stdout. For plan 19 §2 (5.2's TMs) and the Mega ranking's MEGA_RANK_TM (server/Tests/PokeCoreTests/MegaRank.swift).
# --swift: Sources/Data/Machines.swift instead (5.2, plan 19 §11.4) — the 107 machines' moves by number (PokeAPI machines.csv: 1-100 TM,
# 101-107 HM) and, for each species, the numbers it learns as a bitmask (hex, bit n = machine n).
import csv, json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
out = {}
for r in csv.DictReader(open(os.path.join(here, '.cache', 'pokemon_moves.csv'))):
    if r['version_group_id'] == '16' and r['pokemon_move_method_id'] == '4' and int(r['pokemon_id']) <= 721:
        out.setdefault(int(r['pokemon_id']), set()).add(int(r['move_id']))
if '--swift' not in sys.argv:
    json.dump({str(k): sorted(v) for k, v in sorted(out.items())}, sys.stdout, separators=(',', ':'))
    sys.exit()
mpath = os.path.join(here, '.cache', 'machines.csv')                     # https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/machines.csv
machines = {int(r['machine_number']): int(r['move_id']) for r in csv.DictReader(open(mpath)) if r['version_group_id'] == '16'}
assert sorted(machines) == list(range(1, 108)), 'ORAS has 100 TMs and 7 HMs'
number = {m: n for n, m in machines.items()}
masks = []
for dex in range(722):
    bits = 0
    for m in out.get(dex, ()):
        if m in number: bits |= 1 << number[m]
    masks.append('%028x' % bits)
lines = ['// Generated by tools/oras_tms.py --swift (PokeAPI: ORAS = version group 16, machines.csv · pokemon_moves.csv). Do not edit by hand.',
         '// docs/plans/19 §11.4 (5.2): the machines by number (1-100 기술머신, 101-107 비전머신) and who learns which (Machines in Model/MachineRules.swift).',
         '',
         '/// Each machine\'s move; index = its number (0 unused).',
         'let machineMoves: [Int] = [0, ' + ', '.join(str(machines[n]) for n in range(1, 108)) + ']',
         '/// The machines a species learns: index = dex (0 unused), bit n of the hex = machine n.',
         'let machineLearners: [String] = [']
for i in range(0, 722, 8):
    lines.append('    ' + ', '.join('"%s"' % m for m in masks[i:i + 8]) + ',')
lines.append(']')
open(os.path.join(here, '..', 'Sources', 'Data', 'Machines.swift'), 'w').write('\n'.join(lines) + '\n')
print('Sources/Data/Machines.swift: 107 machines, %d species learn one' % sum(1 for m in masks if int(m, 16)))
